// Generate scoped color companions from each page's actual stylesheet order.
// Layout, behavior, content, dark styles and original artwork stay untouched.
const fs=require('fs'),path=require('path'),postcss=require('postcss');
const root=path.resolve(__dirname,'..'),pub=path.join(root,'public');
const prefix=':root[data-appearance="light"]';
function convert(hex,role){
 let h=hex.slice(1);if(h.length===3||h.length===4)h=h.split('').map(x=>x+x).join('');
 const rgb=[0,2,4].map(i=>parseInt(h.slice(i,i+2),16)),l=(rgb[0]*.2126+rgb[1]*.7152+rgb[2]*.0722)/255;
 let result;
 if(role==='background')result=l>.6?'#d3dccd':l>.18?'#dce3d5':'#e8ece2';
 else if(role==='border')result='#536449';
 else if(role==='shadow')result='#3c4c3b';
 else result=l>.82?'#25332c':l>.5?'#3b4b3e':'#33463b';
 return result+(h.length===8?h.slice(6):'');
}
function transformed(css){
 const tree=postcss.parse(css);tree.walkComments(n=>n.remove());
 tree.walkAtRules(a=>{if(/keyframes|font-face/.test(a.name))a.remove();});
 tree.walkRules(rule=>{
  rule.walkDecls(d=>{
   if(!/(?:color|background|border|shadow|fill|stroke|^--)/.test(d.prop)||!/#[\da-f]{3,8}\b/i.test(d.value)){d.remove();return;}
   const role=/background/.test(d.prop)?'background':/border|outline/.test(d.prop)?'border':/shadow/.test(d.prop)?'shadow':'text';
   d.value=d.value.replace(/#[\da-f]{3,8}\b/gi,c=>convert(c,role));
  });
  if(!rule.nodes.length){rule.remove();return;}
  rule.selectors=rule.selectors.map(s=>s.includes(':root')?s.replace(':root',prefix):s.trim()==='html'?prefix:prefix+' '+s);
 });
 tree.walkAtRules(a=>{if(a.nodes&&!a.nodes.length)a.remove();});return tree.toString();
}
const templates=[path.join(pub,'index.html'),...fs.readdirSync(path.join(root,'lib')).filter(x=>x.endsWith('.html')).map(x=>path.join(root,'lib',x))];
for(const file of templates){
 let html=fs.readFileSync(file,'utf8');
 html=html.replace(/<link[^>]+href="\/theme[^" ]*\.css"[^>]*>/g,'').replace(/<script src="\/theme\.js" defer><\/script>/g,'');
 const name=path.basename(file,'.html');
 const sheets=[...html.matchAll(/<link[^>]+href="([^" ]+\.css)"[^>]*>/g)].map(m=>fs.readFileSync(path.join(pub,m[1].replace(/^\//,'')),'utf8'));
 sheets.push(...[...html.matchAll(/<style>([\s\S]*?)<\/style>/g)].map(m=>m[1]));
 fs.writeFileSync(path.join(pub,`theme-light-${name}.css`),'/* Generated by scripts/build-light-theme.cjs. */\n'+sheets.map(transformed).join('\n'));
 html=html.replace('</head>',`<link rel="stylesheet" href="/theme-light-${name}.css"><link rel="stylesheet" href="/theme.css"><script src="/theme.js" defer></script></head>`);
 fs.writeFileSync(file,html);
}
// Reuse the approved palette on both desktop and mobile festival geometry.
const palette={'#966120':'#596d5e','#fae4ad':'#a9b5a1','#e9ba62':'#7c8e7b','#fff3cb':'#b5bfac','#ac782d':'#607562','#f6d68c':'#9daa94','#752738':'#75685a','#f29aac':'#a18c79','#ffd2d1':'#b6a28b','#bb536a':'#8a7868','#384570':'#607a7c','#94bced':'#7b9192','#d6e7ff':'#a0b0ad','#637fbd':'#6e8587','#e5b773':'#9c8768','#d7b66f':'#7a816e','#fff0bf':'#c0c9b8','#ffcfbe':'#c4b7a4','#edc789':'#7c886f','#9dbadf':'#74898b','#c1bce2':'#818783','#f1b3b5':'#968474','#eac47c':'#8b8068','#efa6b4':'#9b897a','#9cbce2':'#738c90','#d9c5fa':'#8d9486','#fff4cd':'#c1b092'};
for(const name of ['festival','festival-mobile']){
 let svg=fs.readFileSync(path.join(pub,'assets',name+'.svg'),'utf8').replace(/#[\da-f]{3,8}\b/gi,c=>palette[c.toLowerCase()]||c);
 svg=svg.replace('<symbol id="star"','<linearGradient id="bronze"><stop stop-color="#76664d"/><stop offset=".4" stop-color="#c1b092"/><stop offset=".7" stop-color="#9c8768"/><stop offset="1" stop-color="#b19f81"/></linearGradient><symbol id="star"');
 svg=svg.replace(/<symbol id="star"[\s\S]*?<\/symbol>/,s=>s.replace('url(#gold)','url(#bronze)').replace('stroke="#c1b092"','fill="#514839" stroke="#c1b092"'));
 fs.writeFileSync(path.join(pub,'assets',name+'-sage.svg'),svg);
}
console.log(`Built light companions for ${templates.length} pages and two native artwork sizes.`);

