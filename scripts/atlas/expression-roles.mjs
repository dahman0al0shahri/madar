import ts from 'typescript';

const binary={
  '&&':'يقيّم الطرف التالي فقط إذا كانت قيمة الطرف الأول صادقة، وإلا يعيد قيمة الطرف الأول.',
  '||':'يعيد الطرف الأول إذا كانت قيمته صادقة، وإلا يقيّم البديل.',
  '??':'يستخدم البديل فقط عند null أو undefined، ويحتفظ بالصفر والنص الفارغ.',
  '===':'يفحص المساواة الصارمة دون تحويل النوع.', '!==':'يفحص اختلاف القيم دون تحويل النوع.',
  '==':'يقارن القيم وفق قواعد المساواة التي تسمح بتحويل الأنواع.', '!=':'يفحص عدم المساواة مع السماح بتحويل الأنواع.',
  '>=':'يشمل حد المساواة في المقارنة مع الحد الأدنى.', '<=':'يشمل حد المساواة في المقارنة مع الحد الأعلى.',
  '<':'يتحقق من ترتيب أصغر تمامًا ويستبعد المساواة.', '>':'يتحقق من ترتيب أكبر تمامًا ويستبعد المساواة.',
  '=':'يكتب القيمة الناتجة عن الطرف الأيمن في الوجهة على اليسار.',
  '+':'يجمع القيم العددية أو يربط النصوص بحسب نوع المعاملات.', '-':'يحسب الفرق بين القيمتين.',
  '*':'يضرب القيمتين.', '/':'يقسم الطرف الأيسر على الأيمن.', '%':'يحسب باقي القسمة.',
  'in':'يفحص وجود المفتاح في الكائن أو سلسلة نماذجه.', 'instanceof':'يتحقق من علاقة الكائن بالنوع عند التشغيل.',
  '|':'ينفذ OR على البتات.', '&':'ينفذ AND على البتات.', '^':'ينفذ XOR على البتات.',
  '>>>':'يزيح البتات إلى اليمين مع ملء البداية بأصفار.', '<<':'يزيح البتات إلى اليسار.', '>>':'يزيح البتات إلى اليمين مع الاحتفاظ ببت الإشارة.',
  '??=':'يكتب البديل إذا كانت القيمة الحالية null أو undefined.', '||=':'يكتب البديل إذا كانت القيمة الحالية غير صادقة.', '&&=':'يكتب القيمة الجديدة فقط إذا كانت الحالية صادقة.'
};
export function expressionRole(n){
  if(ts.isBinaryExpression(n)){
    const op=ts.tokenToString(n.operatorToken.kind)||'';
    return ['operator',op,binary[op]||(op.endsWith('=')?'ينفذ العملية ثم يكتب الناتج في الطرف الأيسر.':'يجمع المعاملين وفق العامل المبين.')];
  }
  if(ts.isPropertyAccessExpression(n)||ts.isElementAccessExpression(n)){
    const writing=ts.isBinaryExpression(n.parent)&&n.parent.left===n&&n.parent.operatorToken.kind>=ts.SyntaxKind.FirstAssignment&&n.parent.operatorToken.kind<=ts.SyntaxKind.LastAssignment;
    return ['member',ts.isPropertyAccessExpression(n)?n.name.text:'[]',writing?'يحدد موضع الكتابة داخل الكائن.':n.questionDotToken?'يقرأ الخاصية إذا وُجد الكائن ويعطي undefined عند غيابه.':'يستخرج الخاصية أو العنصر من الكائن ليستخدمه التعبير المحيط.'];
  }
  if(ts.isPrefixUnaryExpression(n)||ts.isPostfixUnaryExpression(n)){
    const op=ts.tokenToString(n.operator)||'';
    const description={'!':'يعكس القيمة المنطقية.','++':'يزيد القيمة بمقدار واحد.','--':'ينقص القيمة بمقدار واحد.','~':'يعكس البتات.','+':'يحوّل المعامل إلى عدد.','-':'يحسب السالب العددي.'};
    return ['unary',op,description[op]||'يطبق العامل على المعامل.'];
  }
  if(ts.isConditionalExpression(n))return ['branch','?:','يقيّم الشرط ويستخدم تعبير الفرع المختار وحده.'];
  if(ts.isPropertyAssignment(n))return ['objectField',n.name.getText().slice(0,120),'يسمي حقل الناتج ويعين له قيمة التعبير بعد النقطتين.'];
  if(ts.isSpreadElement(n)||ts.isSpreadAssignment(n))return ['expand','...','يفرد عناصر المصدر أو خصائصه في الموضع الحالي.'];
  if(ts.isTemplateSpan(n))return ['interpolate','${…}','يدمج قيمة التعبير المحسوبة في النص المحيط.'];
}
